// Minimal TopoJSON -> GeoJSON extractor for South America.
// Source: world-atlas@2.0.2 countries-50m.json (Natural Earth 1:50m, public domain).
const fs = require('fs');
const topo = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));

const { scale, translate } = topo.transform;

function decodeArc(arc) {
  let x = 0, y = 0;
  return arc.map(p => {
    x += p[0]; y += p[1];
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
}
const arcs = topo.arcs.map(decodeArc);

function ring(idxs) {
  const out = [];
  for (const i of idxs) {
    const a = i < 0 ? arcs[~i].slice().reverse() : arcs[i];
    // drop the joining duplicate point between consecutive arcs
    for (let k = (out.length ? 1 : 0); k < a.length; k++) out.push(a[k]);
  }
  return out;
}

function toGeometry(g) {
  if (g.type === 'Polygon') return { type: 'Polygon', coordinates: g.arcs.map(ring) };
  if (g.type === 'MultiPolygon') return { type: 'MultiPolygon', coordinates: g.arcs.map(p => p.map(ring)) };
  throw new Error('unexpected ' + g.type);
}

// ISO 3166-1 numeric -> our country code
const WANT = {
  '032': 'AR', '068': 'BO', '076': 'BR', '152': 'CL', '170': 'CO', '218': 'EC',
  '328': 'GY', '600': 'PY', '604': 'PE', '740': 'SR', '858': 'UY', '862': 'VE',
  '238': 'FK',
};

const geoms = topo.objects.countries.geometries;
const features = [];

for (const g of geoms) {
  const code = WANT[g.id];
  if (!code) continue;
  features.push({ type: 'Feature', id: code, properties: { name: g.properties.name }, geometry: toGeometry(g) });
}

// French Guiana ships inside France's MultiPolygon in Natural Earth; pull it out by bbox.
const fr = geoms.find(g => g.id === '250');
if (fr) {
  const frGeom = toGeometry(fr);
  const polys = frGeom.type === 'MultiPolygon' ? frGeom.coordinates : [frGeom.coordinates];
  const gf = polys.filter(poly => {
    const pts = poly[0];
    const lon = pts.reduce((s, p) => s + p[0], 0) / pts.length;
    const lat = pts.reduce((s, p) => s + p[1], 0) / pts.length;
    return lon > -56 && lon < -50 && lat > 1 && lat < 7;
  });
  if (gf.length) {
    features.push({
      type: 'Feature', id: 'GF', properties: { name: 'French Guiana' },
      geometry: gf.length === 1 ? { type: 'Polygon', coordinates: gf[0] } : { type: 'MultiPolygon', coordinates: gf },
    });
  } else {
    console.error('WARN: French Guiana polygon not found');
  }
}

// Round coordinates to 3dp (~110m) and drop consecutive duplicates.
function thin(r) {
  const out = [];
  for (const p of r) {
    const q = [Math.round(p[0] * 1000) / 1000, Math.round(p[1] * 1000) / 1000];
    const last = out[out.length - 1];
    if (!last || last[0] !== q[0] || last[1] !== q[1]) out.push(q);
  }
  if (out.length > 3) {
    const a = out[0], b = out[out.length - 1];
    if (a[0] !== b[0] || a[1] !== b[1]) out.push([a[0], a[1]]);
  }
  return out;
}
function thinGeom(g) {
  if (g.type === 'Polygon') g.coordinates = g.coordinates.map(thin).filter(r => r.length > 3);
  else g.coordinates = g.coordinates.map(p => p.map(thin).filter(r => r.length > 3)).filter(p => p.length);
  return g;
}

// Drop tiny slivers, and far-offshore Pacific territories (Galapagos, Easter
// Island, Juan Fernandez). They are real possessions but they sit up to 28 deg
// west of the mainland, which would drag the map's bounding box far out to sea
// and leave the continent squashed into the right-hand side of the frame.
const MIN_AREA = 0.004;   // square degrees
const WEST_LIMIT = -84;   // centroid longitude cutoff
function areaOf(r) {
  let a = 0;
  for (let i = 0, n = r.length - 1; i < n; i++) a += r[i][0] * r[i + 1][1] - r[i + 1][0] * r[i][1];
  return Math.abs(a / 2);
}
for (const f of features) {
  thinGeom(f.geometry);
  if (f.geometry.type === 'MultiPolygon') {
    const kept = f.geometry.coordinates.filter(p => {
      if (areaOf(p[0]) < MIN_AREA) return false;
      const r = p[0];
      const cx = r.reduce((s2, q) => s2 + q[0], 0) / r.length;
      return cx >= WEST_LIMIT;
    });
    if (kept.length) f.geometry.coordinates = kept;
    if (f.geometry.coordinates.length === 1) f.geometry = { type: 'Polygon', coordinates: f.geometry.coordinates[0] };
  }
}

const fc = { type: 'FeatureCollection', features: features.sort((a, b) => a.id.localeCompare(b.id)) };
const out =
  '/* South America country outlines.\n' +
  ' * Derived from Natural Earth 1:50m admin-0 countries (public domain) via world-atlas@2.0.2.\n' +
  ' * Generated by tools/build-geo.js - do not hand-edit.\n' +
  ' */\n' +
  'window.SA_GEO = ' + JSON.stringify(fc) + ';\n';
fs.writeFileSync(process.argv[3], out);

let pts = 0;
for (const f of features) {
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const p of polys) for (const r of p) pts += r.length;
}
console.log('features:', features.map(f => f.id + '=' + f.properties.name).join(', '));
console.log('points:', pts, 'bytes:', out.length);
